function findEquipment() {
    const input = document.getElementById('equipmentName');
    const sectionDisplay = document.getElementById('sectionDisplay');
    const pointDisplay = document.getElementById('pointDisplay');
    const suggestionsList = document.getElementById('suggestionsList');
    const query = input.value.trim().toLowerCase();

    sectionDisplay.classList.remove('found', 'not-found', 'pulse');
    pointDisplay.classList.remove('found', 'not-found', 'pulse');

    if (suggestionsList) {
        suggestionsList.style.display = 'none';
        suggestionsList.innerHTML = '';
    }

    if (!query) {
        sectionDisplay.textContent = '—';
        pointDisplay.textContent = '—';
        return;
    }

    const matches = [];
    for (const [key, value] of Object.entries(equipmentDatabase)) {
        if (key.includes(query) || query.includes(key)) {
            matches.push({ name: key, section: value.section, point: value.point });
        }
    }

    if (matches.length === 0) {
        sectionDisplay.textContent = 'Не найдено';
        pointDisplay.textContent = 'Не найдено';
        sectionDisplay.classList.add('not-found', 'pulse');
        pointDisplay.classList.add('not-found', 'pulse');
        return;
    }

    if (matches.length === 1) {
        const match = matches[0];
        sectionDisplay.textContent = match.section;
        pointDisplay.textContent = match.point;
        sectionDisplay.classList.add('found', 'pulse');
        pointDisplay.classList.add('found', 'pulse');
        return;
    }

    showSuggestions(matches);
}

function showSuggestions(matches) {
    const input = document.getElementById('equipmentName');
    let suggestionsList = document.getElementById('suggestionsList');

    if (!suggestionsList) {
        const container = document.createElement('div');
        container.id = 'suggestionsList';
        container.className = 'suggestions-dropdown';
        container.style.display = 'none';
        input.parentNode.appendChild(container);
        suggestionsList = container;
    }

    suggestionsList.innerHTML = '';
    suggestionsList.style.display = 'block';

    const header = document.createElement('div');
    header.className = 'suggestions-header';
    header.textContent = `🔍 Найдено ${matches.length} совпадений. Выберите:`;
    suggestionsList.appendChild(header);

    matches.forEach(match => {
        const item = document.createElement('div');
        item.className = 'suggestion-item';
        item.innerHTML = `
            <div class="suggestion-name">${match.name}</div>
            <div class="suggestion-class">
                <span class="suggestion-section">${match.section}</span>
                <span class="suggestion-point">${match.point}</span>
            </div>
        `;
        item.addEventListener('click', function() {
            input.value = match.name;
            document.getElementById('sectionDisplay').textContent = match.section;
            document.getElementById('pointDisplay').textContent = match.point;
            document.getElementById('sectionDisplay').classList.add('found', 'pulse');
            document.getElementById('pointDisplay').classList.add('found', 'pulse');
            suggestionsList.style.display = 'none';
        });
        suggestionsList.appendChild(item);
    });
}

